package cn.oyzh.fx.tty;

/**
 * 终端 ASCII 控制字符常量定义。
 *
 * @author oyzh
 * @since 2026-01-05
 */
public class TtyAscii {

    /** 空字符 NUL */
    public static final byte ASCII_NUL = 0;

    /** 转义字符 ESC */
    public static final byte ASCII_ESC = 27;

    /** Ctrl+A 控制字符 */
    public static final byte ASCII_CTRL_A = 0x01;

    /** Ctrl+B 控制字符 */
    public static final byte ASCII_CTRL_B = 0x02;

    /** Ctrl+C 控制字符 */
    public static final byte ASCII_CTRL_C = 0x03;

    /** Ctrl+D 控制字符 */
    public static final byte ASCII_CTRL_D = 0x04;

    /** Ctrl+E 控制字符 */
    public static final byte ASCII_CTRL_E = 0x05;

    /** Ctrl+F 控制字符 */
    public static final byte ASCII_CTRL_F = 0x06;

    /** Ctrl+G 控制字符 */
    public static final byte ASCII_CTRL_G = 0x07;

    /** Ctrl+H（退格）控制字符 */
    public static final byte ASCII_CTRL_H = 0x08;

    /** Ctrl+I（水平制表）控制字符 */
    public static final byte ASCII_CTRL_I = 0x09;

    /** Ctrl+J（换行）控制字符 */
    public static final byte ASCII_CTRL_J = 0x0A;

    /** Ctrl+K 控制字符 */
    public static final byte ASCII_CTRL_K = 0x0B;

    /** Ctrl+L 控制字符 */
    public static final byte ASCII_CTRL_L = 0x0C;

    /** Ctrl+M（回车）控制字符 */
    public static final byte ASCII_CTRL_M = 0x0D;

    /** Ctrl+N 控制字符 */
    public static final byte ASCII_CTRL_N = 0x0E;

    /** Ctrl+O 控制字符 */
    public static final byte ASCII_CTRL_O = 0x0F;

    /** Ctrl+P 控制字符 */
    public static final byte ASCII_CTRL_P = 0x10;

    /** Ctrl+Q 控制字符 */
    public static final byte ASCII_CTRL_Q = 0x11;

    /** Ctrl+R 控制字符 */
    public static final byte ASCII_CTRL_R = 0x12;

    /** Ctrl+S 控制字符 */
    public static final byte ASCII_CTRL_S = 0x13;

    /** Ctrl+T 控制字符 */
    public static final byte ASCII_CTRL_T = 0x14;

    /** Ctrl+U 控制字符 */
    public static final byte ASCII_CTRL_U = 0x15;

    /** Ctrl+V 控制字符 */
    public static final byte ASCII_CTRL_V = 0x16;

    /** Ctrl+W 控制字符 */
    public static final byte ASCII_CTRL_W = 0x17;

    /** Ctrl+X 控制字符 */
    public static final byte ASCII_CTRL_X = 0x18;

    /** Ctrl+Y 控制字符 */
    public static final byte ASCII_CTRL_Y = 0x19;

    /** Ctrl+Z 控制字符 */
    public static final byte ASCII_CTRL_Z = 0x1A;

    /** Ctrl+/ 控制字符 */
    public static final byte ASCII_CTRL_SLASH = 0x1F;

    /** Ctrl+\ 控制字符 */
    public static final byte ASCII_CTRL_BACK_SLASH = 0x1C;
}

#!/bin/sh
# Regenerate input/Layouts.java from a reference server. Run it on the Mac, with the VM's Xvfb up.
#
#   tools/xvfb.sh start
#   tools/gen-layouts.sh                      # the layouts below
#
# Why it exists. A display server cannot compile a keyboard layout - that is a keymap compiler, and
# this is a display server (docs/backlog.md B1) - so the layouts this server serves by name are
# captured off one that can, exactly as the standard X fonts are (D3, tools/GenBitmapFont). The
# capture is the *core* mapping, because that is the request a toolkit resolves its keycodes through,
# and the level a modifier picks is the client's own arithmetic.
#
# The reference is switched with setxkbmap for each name, so each run reads one layout, and each layout
# comes back as a method of its own: a JVM method is capped at 64KB of bytecode, and all of the tables
# in one initialiser is well past it.
set -e
HERE="$(cd "$(dirname "$0")/.." && pwd)"
VM="${XSERVER_VM_HOST:-192.168.22.152}"
VM_REFERENCE_PORT="${VM_REFERENCE_PORT:-6098}"
OUT="$HERE/src/main/java/io/github/oyzh1994/xserver/input/Layouts.java"
LAYOUTS="${LAYOUTS:-us gb de fr es ru cn}"

ENTRIES="$(mktemp -t xs-layouts)"
trap 'rm -f "$ENTRIES"' EXIT

for name in $LAYOUTS; do
    "$HERE/tools/vm.sh" "DISPLAY=:98 setxkbmap $name" >/dev/null 2>&1
    sleep 1
    "$HERE/tools/kit.sh" GenLayouts "$VM" "$VM_REFERENCE_PORT" "$name" >> "$ENTRIES"
done

{
    cat <<'HEADER'
package io.github.oyzh1994.xserver.input;

import java.util.Map;

/**
 * The keyboard layouts this server can be asked for by name, captured off a reference server.
 *
 * <p>Generated by {@code tools/gen-layouts.sh}, and checked in for the reason the bitmap fonts are
 * (D3): a display server cannot compile a layout, so what it serves has to come from one that can, and
 * the tables are what a client sees. Regenerating them needs that server.
 *
 * <p>Each row is one keycode's keysyms, level by level, and the rows are the *core* mapping - which is
 * what a toolkit resolves its keycodes through. The width is the reference's own (seven, on the Xvfb
 * these were taken from), because a client indexes the array with the modifier state its own XKB layer
 * computes, and a narrower table would put the next key's symbols in the wrong place.
 */
final class Layouts {

    /** Index 0 of a row is this keycode. */
    static final int FIRST_KEYCODE = 8;

    /** A layout's keysyms by keycode, or null when this server has no such layout. */
    static int[][] table(String name) {
        return TABLES.get(name);
    }

    private static final Map<String, int[][]> TABLES = Map.ofEntries(
HEADER
    # A trailing comma is fine in an array initialiser and not in a method's argument list, so the last
    # entry is written without one.
    comma=""
    for name in $LAYOUTS; do
        printf '%s            Map.entry("%s", %s())' "$comma" "$name" "$name"
        comma=",
"
    done
    printf '\n'
    cat <<'FOOTER'
    );

    private Layouts() {
    }

FOOTER
    cat "$ENTRIES"
    printf '}\n'
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines)"

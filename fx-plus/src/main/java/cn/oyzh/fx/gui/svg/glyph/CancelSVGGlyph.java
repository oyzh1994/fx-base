package cn.oyzh.fx.gui.svg.glyph;

/**
 * 取消 SVG 图标控件
 *
 * @author oyzh
 * @since 2024/4/11
 */
public class CancelSVGGlyph extends CloseSVGGlyph {

    /**
     * 构造 SVG 图标控件
     */
    public CancelSVGGlyph() {
        super();
    }

    /**
     * 构造指定尺寸的 SVG 图标控件
     *
     * @param size 尺寸
     */
    public CancelSVGGlyph(String size) {
        super();
        this.setSizeStr(size);
    }
}
